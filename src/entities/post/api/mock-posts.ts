const make = (intro: string[], withImages: boolean): PostBlock[] => {
  const blocks: PostBlock[] = intro.map((text) => ({ type: 'p', text }))
  blocks.push({ type: 'h', text: 'С чего начать' })
  blocks.push({ type: 'p', text: pool[0] })
  if (withImages) blocks.push({ type: 'image', src: postCode, alt: 'Код на экране ноутбука' })
  blocks.push({ type: 'p', text: pool[1] }, { type: 'p', text: pool[2] })
  blocks.push({ type: 'h', text: 'Что важно учесть' })
  blocks.push({ type: 'p', text: pool[3] })
  if (withImages) blocks.push({ type: 'image', src: postGlasses, alt: 'Очки на ноутбуке рядом со смартфоном и мышью' })
  blocks.push({ type: 'p', text: pool[4] }, { type: 'p', text: pool[5] })
  return blocks
}

